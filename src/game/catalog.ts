function buildCatalog(): CatalogItem[] {
  const items: CatalogItem[] = [];
  let index = 1;

  for (const tpl of BASE_TEMPLATES) {
    for (const style of STYLE_VARIANTS) {
      const scaledMaterials: Partial<ResourceStock> = {};
      for (const [k, v] of Object.entries(tpl.materials)) {
        if (typeof v === 'number') {
          scaledMaterials[k as keyof ResourceStock] = Math.max(1, Math.round(v * style.costMult));
        }
      }

      const scaledProduction: Partial<ResourceStock> | undefined = tpl.productionPerMin
        ? Object.fromEntries(
            Object.entries(tpl.productionPerMin).map(([k, v]) => [
              k,
              Math.max(1, Math.round((v ?? 0) * style.yieldMult)),
            ])
          )
        : undefined;

      const powerRaw =
        tpl.powerMW > 0
          ? Math.round(tpl.powerMW * style.yieldMult * 10) / 10
          : Math.round(tpl.powerMW * (style.powerMult ?? 1.0) * 10) / 10;

      const pollutionRaw =
        tpl.pollutionDelta < 0
          ? Math.round(tpl.pollutionDelta * (style.tier >= 3 ? 1.15 : 1.0) * 10) / 10
          : Math.round(tpl.pollutionDelta * (style.tier === 3 ? 0.75 : 1.0) * 10) / 10;

      const code = `${tpl.codePrefix}-${String(index).padStart(3, '0')}`;
      items.push({
        id: code.toLowerCase(),
        code,
        nameFa: `${tpl.nameFa} — ${style.suffixFa}`,
        nameEn: `${tpl.nameEn} (${style.suffixEn})`,
        descFa: tpl.descFa,
        descEn: tpl.descEn,
        category: tpl.category,
        archetype: tpl.archetype,
        tier: style.tier,
        footprintW: Math.round(tpl.footprintW * Math.min(1.12, style.scaleVar) * 10) / 10,
        footprintD: Math.round(tpl.footprintD * Math.min(1.12, style.scaleVar) * 10) / 10,
        heightM: Math.round(tpl.heightM * style.scaleVar * 10) / 10,
        cost: Math.round(tpl.cost * style.costMult),
        buildTimeSec: Math.max(5, Math.round(tpl.buildTimeSec * style.timeMult)),
        materials: scaledMaterials,
        upkeepPerMin: Math.round(tpl.upkeepPerMin * (0.9 + style.costMult * 0.12)),
        taxYieldPerMin: Math.round(tpl.taxYieldPerMin * style.yieldMult),
        productionPerMin: scaledProduction,
        jobs: Math.round(tpl.jobs * (tpl.jobs > 0 ? style.yieldMult : 1)),
        housing: Math.round(tpl.housing * (tpl.housing > 0 ? style.yieldMult : 1)),
        powerMW: powerRaw,
        waterML: tpl.waterML,
        happinessDelta: tpl.happinessDelta + (style.tier >= 4 ? 1 : 0),
        pollutionDelta: pollutionRaw,
        wallColor: style.wallColor,
        accentColor: style.accentColor,
        scaleVariation: style.scaleVar,
      });
      index++;
    }
  }

  return items;
}

export const CATALOG_ITEMS: CatalogItem[] = buildCatalog();

export const CATALOG_MAP: Map<string, CatalogItem> = new Map(
  CATALOG_ITEMS.map((item) => [item.id, item])
);

export function findCatalogByPrefix(codePrefix: string, variantIndex = 0): CatalogItem {
  const lower = codePrefix.toLowerCase();
  const matches = CATALOG_ITEMS.filter((item) => item.id.startsWith(`${lower}-`));
  if (matches.length === 0) {
    return CATALOG_ITEMS[0];
  }
  return matches[Math.min(variantIndex, matches.length - 1)];
}

